## LLM
def get_llm():
    model_id = 'ibm/granite-3-2b-instruct'
    parameters = {
        GenParams.DECODING_METHOD: 'greedy',
        GenParams.MAX_NEW_TOKENS: 256
    }
    project_id = 'skills-network'
    watsonx_llm = WatsonxLLM(
        model_id=model_id,
        url='https://us-south.ml.cloud.ibm.com',
        project_id=project_id,
        params=parameters
    )
    return watsonx_llm

 ## Document Loader
def document_loader(file):
    loader = PyPDFLoader(file.name)
    loaded_document = loader.load()
    return loaded_document
    
## Text Spliter
def text_splitter(data):
    text_splitter = RecursiveCharacterTextSplitter(
        chunk_size=1000,
        chunk_overlap=50,
        length_function=len,
    )
    chunks = text_splitter.split_documents(data)
    return chunks

## Embedding Model
def watsonx_embedding():
    embed_params = {
        EmbedParams.truncate_input_tokens: 128,
        EmbedParams.input_text: True,
    }
    watosnx_embedding = WatsonxEmbeddings(
        model_id='ibm/slate-125m-english-rtrvr',
        url='https://us-south.ml.cloud.ibm.com',
        project_id='skills-network',
        params=embed_params
    )
    return watosnx_embedding

## vector db
def vector_database(chunks):
    embedding_model = watsonx_embedding()
    vectordb = Chroma.from_documents(chunks, embedding_model)
    return vectordb

## Retriever
def retriever(file):
    splits = document_loader(file)
    chunks = text_splitter(splits)
    vectordb = vector_database(chunks)
    retriever = vectordb.as_retriever()
    return retriever

## QA Chain
def retriever_qa(file, query):
    llm = get_llm()
    retriever_obj = retriever(file)
    qa = RetrievalQA.from_chain_type(
        llm=llm,
        chain_type='stuff', 
        retriever=retriever_obj, 
        return_source_documents=False
    )
    response = qa.invoke(query)
    return response['result']

## Create Gradio Interface
rag_applcation = gr.Interface(
    fn=retriever_qa,
    allow_flagging='manual',
    inputs=[
        gr.File(label="Upload PDF File", file_count="single", file_types=['.pdf'], type='filepath'),
        gr.Textbox(label="Input Query", lines=2, placeholder="Type your question here")
    ],
    outputs=gr.Textbox(label="LLM Response"),
    title="LLM RAG LangChain",
    description="Upload a PDF document and ask any question"
)
rag_applcation.launch()